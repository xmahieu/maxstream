HEADER = '''# Kodi Media Center language file
# Addon Name: MaxStream IPTV
# Addon id: script.maxstream
msgid ""
msgstr ""
"Project-Id-Version: script.maxstream\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Language: {lang}\\n"

'''


def esc(text):
    return text.replace('\\', '\\\\').replace('"', '\\"')


def write(root, folder, lang, index):
    path = os.path.join(root, 'resources', 'language', folder)
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, 'strings.po'), 'w', encoding='utf-8', newline='\n') as out:
        out.write(HEADER.format(lang=lang))
        for sid in sorted(S):
            en = S[sid][0]
            out.write('msgctxt "#%d"\nmsgid "%s"\nmsgstr "%s"\n\n' % (sid, esc(en), '' if index == 0 else esc(S[sid][index])))


if __name__ == '__main__':
    import sys
    root = sys.argv[1]
    write(root, 'resource.language.en_gb', 'en_GB', 0)
    write(root, 'resource.language.fr_fr', 'fr_FR', 1)
